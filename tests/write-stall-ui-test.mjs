	const phaseKinds = [['read', '读取上次进度'], ['write', '实现 jobs 服务'], ['write', '补 migrations'], ['bash', '运行测试'], ['edit', '修复测试'], ['bash', 'git commit']];
	const phaseSteps = phaseKinds.map(([kind, title], index) => ({ id: `phase-${index}`, messageId: `phase-${index}`, title, detail: `**${title}**：检查 \`jobs\``, status: 'done', startedAt: 1000 + index * 10000, endedAt: 3000 + index * 10000, artifacts: [{ toolCallId: `phase-tool-${index}`, kind, label: title }] }));
