	await page.locator('.agent-silence').waitFor();
	socket.send(JSON.stringify({ type: 'agent_silence', conversationId: state.conversationId, phase: 'active', since: Date.now(), activity: 'model' }));
	state = { ...state, rev: state.rev + 1, messages: [waitingUser('waiting-content', 2)], streamingMessage: { id: 'thinking-start', role: 'assistant', model: 'glm-5.3', timestamp: Date.now(), content: [{ type: 'thinking', thinking: '正在检查项目' }] } };
