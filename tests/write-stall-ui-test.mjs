	state = { ...state, rev: state.rev + 1, streamingMessage: { id: 'thinking-start', role: 'assistant', model: 'glm-5.3', timestamp: Date.now(), content: [{ type: 'text', text: '已经检查好了。' }] } };
	socket.send(JSON.stringify({ type: 'snapshot', state }));
