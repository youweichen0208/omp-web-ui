	assert.equal(await page.locator('.waiting-header-status').count(), 0, 'visible reply replaces the waiting hint');
	const replyGap = await page.locator('.msg-assistant:has(.msg-text)').last().evaluate((element) => element.querySelector('.msg-text').getBoundingClientRect().top - element.querySelector('.msg-meta').getBoundingClientRect().bottom);
	assert(replyGap >= 7 && replyGap <= 9, `heading to reply must be 8px, got ${replyGap}`);
	await page.setViewportSize({ width: 390, height: 900 });
	state = { ...state, rev: state.rev + 1, messages: [waitingUser('waiting-mobile', 10)], streamingMessage: null };
	socket.send(JSON.stringify({ type: 'snapshot', state }));
	await page.locator('.waiting-header-status', { hasText: '正在分析请求' }).waitFor();
	assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'waiting header fits a narrow viewport');
