import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,mkdirSync,rmSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {setTimeout as sleep} from 'node:timers/promises';
import {chromium} from 'playwright-core';
import {CHROME_PATH} from './lib/chrome.mjs';
import {portUp} from './lib/port-utils.mjs';
const port=9263, root=mkdtempSync(join(tmpdir(),'pi-fluid-'));
const cwd=join(root,'pi-harness');mkdirSync(cwd);writeFileSync(join(cwd,'README.md'),'# Project\n');
const plugin=join(root,'data','plugins','polish-fixture');mkdirSync(join(plugin,'client'),{recursive:true});
writeFileSync(join(plugin,'manifest.json'),JSON.stringify({name:'Fixture view'}));
writeFileSync(join(plugin,'client','entry.mjs'),`let attempts=0;export default {mount(el){if(++attempts===1)throw new Error('fixture');el.innerHTML='<h2>Plugin recovered</h2><button>Fixture action</button>';return ()=>{el.textContent='';};}};`);
let server,browser;
try {
	assert.equal(await portUp(port),false);
	server=spawn(process.execPath,['dist/server/index.js'],{env:{...process.env,PORT:String(port),PI_WEB_CWD:cwd,PI_WEB_DATA_DIR:join(root,'data'),PI_CODING_AGENT_DIR:join(root,'agent')},stdio:'ignore'});
	for(let i=0;i<100&&!await portUp(port);i++)await sleep(150);
	assert(await portUp(port));
	browser=await chromium.launch({executablePath:CHROME_PATH});
	mkdirSync('tests/scratch',{recursive:true});
	const page=await browser.newPage({viewport:{width:1440,height:960}});
	const errors=[];page.on('pageerror',e=>errors.push(String(e)));
	await page.goto(`http://localhost:${port}`);
	await page.locator('.setup-modal .modal-close').click();
	await page.locator('.workspace-group-manager input').fill('Engineering');
	await page.locator('.workspace-group-actions button[type=submit]').click();
	await page.locator('.workspace-outside button').click();
	await page.locator('.project-item.active').waitFor();
	await page.getByRole('tab',{name:'Fixture view',exact:true}).click();
	await page.locator('.plugin-view-error').waitFor();
	assert.equal(await page.locator('.plugin-view-error').getAttribute('role'),'alert');
	await page.locator('.plugin-view-error button').click();
	await page.getByRole('heading',{name:'Plugin recovered'}).waitFor();
	assert.equal(await page.locator('.plugin-view-error').count(),0);
	await page.setViewportSize({width:375,height:844});
	assert(await page.getByRole('button',{name:'Fixture action'}).isVisible());
	assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
	await page.getByRole('tab',{name:'对话',exact:true}).click();
	await page.getByRole('tab',{name:'Fixture view',exact:true}).click();
	await page.getByRole('heading',{name:'Plugin recovered'}).waitFor();
	assert.deepEqual(errors,[]);
	console.log('PASS plugin host: mount error, retry, view persistence and mobile bounds');
} finally { await browser?.close();server?.kill('SIGTERM');await sleep(300);rmSync(root,{recursive:true,force:true}); }
