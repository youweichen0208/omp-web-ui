// Exercise the real SDK runtime and extension loader without model requests.
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createAgentSessionRuntime, SessionManager } from "@earendil-works/pi-coding-agent";
import { ClientSession } from "../dist/server/agent-service.js";
import { ClientStateStore } from "../dist/server/client-state.js";
import { ThinkingDurationStore } from "../dist/server/thinking-timing.js";
const root = mkdtempSync(join(tmpdir(), "pi-restart-session-"));
process.env.PI_CODING_AGENT_DIR = join(root, "agent");
const extensions = join(process.env.PI_CODING_AGENT_DIR, "extensions");
mkdirSync(extensions, { recursive: true });
const install = version => writeFileSync(join(extensions, "probe.ts"), `export default function(pi) {
 let calls = 0;
 pi.registerCommand("probe", { description: "Restart probe", handler: async (_, ctx) => ctx.ui.notify("${version}:" + (++calls), "info") });
}`);
let cs;
try {
	install("v1");
	cs = await ClientSession.create("restart", root, new ClientStateStore(join(root, "state.json")), new ThinkingDurationStore(join(root, "thinking.json")));
	const wire = []; cs.attachSink(message => wire.push(message));
	const conv = cs.conv, previous = conv.session, terminals = conv.terminals;
	const manager = previous.sessionManager;
	manager.appendMessage({ role: "user", content: "Keep this exact branch", timestamp: Date.now() });
	manager.appendMessage({ role: "assistant", content: [{ type: "text", text: "Preserved response" }], api: "openai-completions", provider: "fixture", model: "fixture", usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } }, stopReason: "stop", timestamp: Date.now() });
	previous.agent.state.messages = manager.buildSessionContext().messages;
	await new Promise(resolve => setTimeout(resolve, 50));
	await conv.tree.waitForVerification();
	await cs.prompt("/probe");
	await cs.prompt("/probe");
	assert(wire.some(m => m.type === "notice" && m.text === "v1:2"), JSON.stringify(wire.filter(m => m.type === "notice")));
	const otherRuntime = await createAgentSessionRuntime(cs.makeRuntimeFactory(), { cwd: root, agentDir: process.env.PI_CODING_AGENT_DIR, sessionManager: SessionManager.inMemory(root) });
	const other = cs.makeConversation(otherRuntime, "other", cs.makeTerminalManager("other", root)); cs.convs.set(other.id, other);
	await cs.bindSession(other);
	const history = manager.getBranch(), leaf = manager.getLeafId(), sessionId = previous.sessionId;
	install("v2");
	await cs.prompt("/restart", undefined, false, "restart-request");
	assert(wire.some(m => m.type === "prompt_result" && m.requestId === "restart-request" && m.ok));
	assert(conv.session !== previous, "restart must create a fresh session");
	assert(other.session === otherRuntime.session, "other conversations retain their runtime");
	assert(cs.convs.get(other.id) === other);
	assert.equal(conv.session.sessionManager, manager);
	assert.equal(conv.session.sessionId, sessionId);
	assert.equal(conv.terminals, terminals);
	assert.equal(manager.getLeafId(), leaf);
	assert.deepEqual(manager.getBranch(), history);
	await cs.prompt("/probe");
	assert(wire.some(m => m.type === "notice" && m.text === "v2:1"));
	assert.equal(conv.session.messages[0].content, "Keep this exact branch");
	const healthy = conv.session, factory = cs.makeRuntimeFactory;
	cs.onEvent(conv, { type: "compaction_start", reason: "manual" });
	await assert.rejects(cs.restartSession(conv.id), /停止当前任务/);
	cs.onEvent(conv, { type: "agent_settled" });
	cs.makeRuntimeFactory = () => async () => { throw new Error("fixture preparation failure"); };
	await assert.rejects(cs.restartSession(conv.id), /fixture preparation failure/);
	assert.equal(conv.session, healthy); assert.equal(cs.switchingWorkspace, false);
	cs.makeRuntimeFactory = factory;
	await cs.prompt("/probe");
	assert(wire.some(m => m.type === "notice" && m.text === "v2:2"));
	let release, started;
	const gate = new Promise(resolve => { release = resolve; });
	const ready = new Promise(resolve => { started = resolve; });
	cs.makeRuntimeFactory = (...args) => {
		const create = factory.apply(cs, args);
		return async options => { started(); await gate; return create(options); };
	};
	const restarting = cs.restartSession(conv.id);
	await ready;
	await assert.rejects(cs.restartSession(conv.id), /切换或重启/);
	await cs.setCwd(tmpdir(), "during-restart", "ui");
	assert(wire.some(m => m.type === "cwd_result" && m.requestId === "during-restart" && !m.ok));
	assert.equal(cs.cwd, root);
	assert.equal(await cs.newChat(true), false);
	release(); await restarting;
	assert.equal(cs.switchingWorkspace, false);
	console.log("PASS restart refreshes extension code/state, retains exact history and terminals, recovers preparation failure, and rejects concurrent navigation/restart");
} finally {
	await cs?.dispose(); rmSync(root, { recursive: true, force: true });
}
