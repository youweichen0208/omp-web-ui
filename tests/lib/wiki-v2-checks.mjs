import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
export async function checkWikiV2(page, cwd) {
	await page.locator('.wiki-tree-row[title="toolbar.md"]').click();
	const editor = page.locator('.wiki-prose .fp-rich-document');
	await page.locator('.wiki-document-heading h1', { hasText: 'Toolbar fixture' }).waitFor();
	if (await page.locator('.wiki-chat-panel').isVisible()) await page.locator('.wiki-chat-toggle').click();
	const end = async () => { await editor.evaluate(el => { el.focus(); const r = document.createRange(); r.selectNodeContents(el); r.collapse(false); const s = getSelection(); s.removeAllRanges(); s.addRange(r); }); await page.keyboard.press('Enter'); };
	for (const width of [1100, 1440]) {
		await page.setViewportSize({ width, height: 1000 });
		assert(await page.locator('.wiki-insert-toolbar').evaluate(el => el.scrollWidth <= el.clientWidth));
		assert.equal(await page.locator('.wiki-document-toolbar').evaluate(el => el.getBoundingClientRect().height), 44);
		assert.equal(await page.locator('.wiki-document-heading h1').evaluate(el => getComputedStyle(el).fontSize), '34px');
		assert.equal(await editor.locator('h2').evaluate(el => getComputedStyle(el).fontSize), '22px');
		await page.screenshot({ path: `tests/scratch/wiki34-${width}.png` });
	}
	await page.getByRole('button', { name: '宽版（隐藏两侧）', exact: true }).click();
	assert.equal(await editor.evaluate(el => Math.round(el.getBoundingClientRect().width)), 1000);
	await page.keyboard.press('Meta+j');
	assert.equal(await page.locator('.wiki-workbench.is-focused').count(), 0);
	await page.locator('.wiki-chat-toggle').click();
	await end();
	await editor.locator('[data-wiki-placeholder]').waitFor();
	await page.locator('.wiki-insert-toolbar button').nth(3).click();
	assert.equal(await page.locator('.wiki-table-grid button').count(), 48);
	for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowRight');
	for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowDown');
	await page.keyboard.press('Enter');
	assert.equal(await editor.locator('table tr').count(), 6);
	assert.equal(await editor.locator('table th').count(), 8);
	await page.keyboard.type('Header marker');
	await end();
	await page.locator('.wiki-insert-toolbar button').nth(4).click();
	await page.locator('.wiki-language-picker input').fill('merm');
	await page.locator('.wiki-language-picker button').click();
	await editor.locator('.wiki-mermaid-preview svg.flowchart').waitFor();
	assert((await editor.locator('code.language-mermaid').innerText()).includes('flowchart LR'));
	await page.keyboard.press('Meta+s');
	await page.locator('.wiki-save-status.saved').waitFor();
	const markdown = readFileSync(join(cwd, 'toolbar.md'), 'utf8');
	assert(markdown.includes('Header marker'));
	assert(markdown.includes('```mermaid\nflowchart LR'));
	assert(!markdown.includes('<svg') && !markdown.includes('wiki-mermaid-preview'));
	await end();
	await page.locator('.wiki-more-insert').click();
	const more = await page.locator('.wiki-more-items button > span:nth-child(2)').allTextContents();
	await page.keyboard.press('Escape');
	await page.keyboard.type('/');
	await page.locator('.wiki-slash-menu').waitFor();
	assert.equal(await page.locator('.wiki-slash-menu [role="option"]').count(), more.length);
	await page.keyboard.press('Escape');
	await page.keyboard.press('Backspace');
	await page.keyboard.press('Meta+s');
	await page.locator('.wiki-save-status.saved').waitFor();
	await page.screenshot({ path: 'tests/scratch/wiki34-inserted.png' });
	await page.locator('.wiki-tree-row[title="README.md"]').click();
	await page.locator('.wiki-document-heading h1', { hasText: '风控规则' }).waitFor();
}
